package foreverscouting_test

import (
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/Emyrk/chronicle-sidekick/internal/foreverscouting"
)

func TestExtractPreservesExactScoutingExpression(t *testing.T) {
	t.Parallel()
	const input = `-- generated by WoW
ChronicleCompanionForeverDB = {
  profile = true;
  ["scouting"] = { -- preserve this comment
    ["Player-1"] = {
      deltas = { -4, 0, 12.5e2, },
      note = "escaped \"quote\" and \n newline",
      [1700000000] = false,
      [1700000000] = "",
    },
  },
}
-- trailing comment
`
	const want = `{ -- preserve this comment
    ["Player-1"] = {
      deltas = { -4, 0, 12.5e2, },
      note = "escaped \"quote\" and \n newline",
      [1700000000] = false,
      [1700000000] = "",
    },
  }`
	got, present, err := foreverscouting.Extract([]byte(input))
	require.NoError(t, err)
	require.True(t, present)
	require.Equal(t, want, got)
}

func TestExtractOmissionAndTypeRules(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name    string
		value   string
		present bool
		wantErr string
	}{
		{name: "missing", value: `{ other = 1 }`},
		{name: "nil", value: `{ scouting = nil }`},
		{name: "false", value: `{ scouting = false }`},
		{name: "empty table", value: `{ scouting = {} }`},
		{name: "empty string is not an empty table", value: `{ scouting = "" }`, wantErr: "scouting must be a table"},
		{name: "one false entry is nonempty", value: `{ scouting = { false } }`, present: true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			_, present, err := foreverscouting.Extract([]byte("ChronicleCompanionForeverDB = " + tc.value))
			if tc.wantErr != "" {
				require.ErrorContains(t, err, tc.wantErr)
				return
			}
			require.NoError(t, err)
			require.Equal(t, tc.present, present)
		})
	}
}

func TestExtractRejectsExecutableOrAmbiguousLua(t *testing.T) {
	t.Parallel()
	for _, body := range []string{
		`ChronicleCompanionForeverDB = loadstring("bad")()`,
		`ChronicleCompanionForeverDB = { scouting = { value = os.time() } }`,
		`ChronicleCompanionForeverDB = { scouting = { value = 1 + 2 } }`,
		`ChronicleCompanionForeverDB = { scouting = {} }; evil()`,
		`OtherGlobal = { scouting = { value = 1 } }`,
		`ChronicleCompanionForeverDB = { scouting = {}, scouting = { value = 1 } }`,
	} {
		_, _, err := foreverscouting.Extract([]byte(body))
		require.Error(t, err, body)
	}
}
